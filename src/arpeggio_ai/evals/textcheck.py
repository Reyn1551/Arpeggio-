"""Text-check hidden tests for ``eval new --check-file --check-pattern`` (M0.6).

The generated test is a dependency-free Node test (``node:test``) that reads one file of
the repository and asserts that a regular expression matches its text. It becomes the
task's only hidden test and its done criterion: ``node --test <path>``.

Before anything is written, the pattern is checked with Python's ``re`` against the file
at ``base`` (it must **not** match; a missing file does not match) and at ``solution`` (it
**must** match). At run time the pattern is a JavaScript ``RegExp`` without flags, so use
the syntax both engines share (character classes, ``\\d``, ``\\s``, groups, ``|``, ``^``
and ``$`` per string, not per line); Python-only syntax such as ``(?P<name>...)`` or
inline flags may behave differently. Generated files are ASCII: every string in the test
is a JSON literal with non-ASCII characters escaped.
"""

import json
import re
from dataclasses import dataclass

HIDDEN_DIR = "tests/arpeggio-hidden"


@dataclass(frozen=True, slots=True)
class TextCheck:
    file: str  # repo-relative POSIX path
    pattern: str
    name: str | None = None


class TextCheckError(ValueError):
    """The pattern does not discriminate between base and solution, or is invalid."""


def hidden_path(task_id: str) -> str:
    return f"{HIDDEN_DIR}/{task_id}.test.mjs"


def verify(check: TextCheck, at_base: str | None, at_solution: str | None) -> None:
    """Refuse unless the pattern fails at base and matches at solution (Python ``re``)."""
    try:
        compiled = re.compile(check.pattern)
    except re.error as error:
        raise TextCheckError(f"--check-pattern is not a valid regular expression: {error}") from None
    if at_base is not None and compiled.search(at_base):
        raise TextCheckError(
            f"--check-pattern already matches {check.file} at base, so the check would not"
            " discriminate; make the pattern specific to the change"
        )
    if at_solution is None:
        raise TextCheckError(f"{check.file} does not exist at the solution commit")
    if not compiled.search(at_solution):
        raise TextCheckError(f"--check-pattern does not match {check.file} at the solution commit")


def render(task_id: str, check: TextCheck) -> bytes:
    """The Node test file, ASCII only, without BOM, LF line endings."""
    name = check.name or f"{check.file} matches the expected text"
    text = (
        f"// Hidden test generated by `arpeggio eval new` for {task_id}. Never shown to a model.\n"
        'import { test } from "node:test";\n'
        'import assert from "node:assert/strict";\n'
        'import { readFileSync } from "node:fs";\n'
        "\n"
        f"const FILE = {json.dumps(check.file)};\n"
        f"const PATTERN = new RegExp({json.dumps(check.pattern)});\n"
        "\n"
        f"test({json.dumps(name)}, () => {{\n"
        '  const text = readFileSync(FILE, "utf8");\n'
        "  assert.match(text, PATTERN);\n"
        "});\n"
    )
    return text.encode("ascii")
